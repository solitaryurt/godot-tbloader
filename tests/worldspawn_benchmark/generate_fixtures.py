#!/usr/bin/env python3
"""Generate deterministic worldspawn renderer benchmark maps and their manifest."""

import argparse
import hashlib
import json
from pathlib import Path


TEXTURE = "benchmark/grid"


def brush(lo, hi):
    x0, y0, z0 = lo
    x1, y1, z1 = hi
    return "\n".join((
        "{",
        f"( {x1} {y0} {z0} ) ( {x1} {y1} {z1} ) ( {x1} {y1} {z0} ) {TEXTURE} 0 0 0 1 1",
        f"( {x0} {y0} {z1} ) ( {x0} {y1} {z0} ) ( {x0} {y1} {z1} ) {TEXTURE} 0 0 0 1 1",
        f"( {x0} {y1} {z0} ) ( {x1} {y1} {z1} ) ( {x0} {y1} {z1} ) {TEXTURE} 0 0 0 1 1",
        f"( {x0} {y0} {z1} ) ( {x1} {y0} {z0} ) ( {x0} {y0} {z0} ) {TEXTURE} 0 0 0 1 1",
        f"( {x0} {y0} {z1} ) ( {x1} {y1} {z1} ) ( {x1} {y0} {z1} ) {TEXTURE} 0 0 0 1 1",
        f"( {x1} {y0} {z0} ) ( {x0} {y1} {z0} ) ( {x0} {y0} {z0} ) {TEXTURE} 0 0 0 1 1",
        "}",
    ))


def indoor():
    boxes = []
    # A 12 x 10 room grid. Floors, ceilings, and alternating door gaps provide
    # repeatable frustum and occlusion rejection without overlapping brushes.
    room, wall, height = 16, 1, 8
    width, depth = 12 * room, 10 * room
    boxes.extend([((0, 0, -1), (width, depth, 0)), ((0, 0, height), (width, depth, height + 1))])
    for x in range(0, width + 1, room):
        for cell in range(10):
            y = cell * room
            door = (cell + x // room) % 3
            if door == 0 and 0 < x < width:
                boxes.extend([((x, y, 0), (x + wall, y + 6, height)),
                              ((x, y + 10, 0), (x + wall, y + room, height))])
            else:
                boxes.append(((x, y, 0), (x + wall, y + room, height)))
    for y in range(0, depth + 1, room):
        for cell in range(12):
            x = cell * room
            door = (cell + y // room) % 4
            if door == 0 and 0 < y < depth:
                boxes.extend([((x, y, 0), (x + 6, y + wall, height)),
                              ((x + 10, y, 0), (x + room, y + wall, height))])
            else:
                boxes.append(((x, y, 0), (x + room, y + wall, height)))
    return boxes, {
        "fully_visible": {"position": [80, 225, 96], "target": [80, 0, 96]},
        "frustum_limited": {"position": [8, 4, 8], "target": [8, 4, 88]},
        "heavily_occluded": {"position": [8, 4, 8], "target": [8, 4, 24]},
        "occluder": {"position": [8, 4, 16.5], "size": [16, 8, 1]},
    }


def mixed():
    boxes = []
    # Open plaza on one side and a deterministic block of hollow buildings on the other.
    boxes.append(((0, 0, -1), (224, 160, 0)))
    for gx in range(6):
        for gy in range(5):
            x, y = 8 + gx * 24, 8 + gy * 28
            h = 8 + ((gx * 7 + gy * 3) % 4) * 4
            boxes.extend([((x, y, 0), (x + 20, y + 1, h)), ((x, y + 19, 0), (x + 20, y + 20, h)),
                          ((x, y + 1, 0), (x + 1, y + 19, h)), ((x + 19, y + 1, 0), (x + 20, y + 19, h)),
                          ((x, y, h), (x + 20, y + 20, h + 1))])
    for x in range(156, 220, 4):
        for y in range(4, 156, 4):
            h = 1 + ((x * 13 + y * 17) % 5)
            boxes.append(((x, y, 0), (x + 3, y + 3, h)))
    return boxes, {
        "fully_visible": {"position": [80, 250, 112], "target": [80, 0, 112]},
        "frustum_limited": {"position": [72, 7, 150], "target": [72, 5, 80]},
        "heavily_occluded": {"position": [18, 4, 18], "target": [18, 4, 42]},
        "occluder": {"position": [18, 4, 27.5], "size": [18, 8, 1]},
    }


def open_map():
    boxes = []
    # 32 x 32 separated terrain blocks ensure the 1,000-chunk profile is meaningful.
    for x in range(32):
        for y in range(32):
            z = (x * 11 + y * 7 + (x ^ y) * 3) % 4
            boxes.append(((x * 4, y * 4, -1), (x * 4 + 3, y * 4 + 3, z)))
    return boxes, {
        "fully_visible": {"position": [64, 180, 64], "target": [64, 0, 64]},
        "frustum_limited": {"position": [4, 4, 4], "target": [4, 3, 90]},
        "heavily_occluded": {"position": [4, 2, 4], "target": [4, 2, 28]},
        "occluder": {"position": [4, 2, 7.5], "size": [3, 6, 3]},
    }


def generate(output):
    output.mkdir(parents=True, exist_ok=True)
    manifest = {"schema": 1, "coordinate_system": "Godot (map y,z,x), inverse_scale=1", "fixtures": {}}
    for name, factory in (("indoor", indoor), ("mixed", mixed), ("open", open_map)):
        boxes, cameras = factory()
        text = "// Generated by tests/worldspawn_benchmark/generate_fixtures.py\n{\n\"classname\" \"worldspawn\"\n"
        text += "\n".join(brush(lo, hi) for lo, hi in boxes) + "\n}\n"
        path = output / f"{name}.map"
        path.write_text(text)
        manifest["fixtures"][name] = {
            "map": path.name,
            "brushes": len(boxes),
            "expected_triangles": len(boxes) * 12,
            "sha256": hashlib.sha256(text.encode()).hexdigest(),
            "cameras": cameras,
        }
    encoded = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    (output / "manifest.json").write_text(encoded)
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="generate twice and verify byte identity")
    args = parser.parse_args()
    generate(args.output)
    if args.check:
        first = {p.name: p.read_bytes() for p in args.output.iterdir() if p.is_file()}
        generate(args.output)
        second = {p.name: p.read_bytes() for p in args.output.iterdir() if p.is_file()}
        if first != second:
            raise SystemExit("fixture generation is not deterministic")
    print(json.dumps({"output": str(args.output), "status": "PASS"}, sort_keys=True))


if __name__ == "__main__":
    main()
